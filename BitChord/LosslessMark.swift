/// What a stream's own description says it is.
enum StreamQualityKind {
    case hiResLossless
    case lossless
    case highQuality

    init?(label: String?) {
        guard let label, !label.isEmpty else { return nil }
        let lowered = label.lowercased()
        if lowered.contains("flac") || lowered.contains("alac") || lowered.contains("lossless") {
            self = lowered.contains("24-bit") || lowered.contains("hi-res") || lowered.contains("hi_res")
                ? .hiResLossless
                : .lossless
            return
        }
        if lowered.contains("320") || lowered.contains("256") || lowered.contains("high") {
            self = .highQuality
            return
        }
        return nil
    }

    var text: String {
        switch self {
        case .hiResLossless: return "Hi-Res Lossless"
        case .lossless: return "Lossless"
        case .highQuality: return "High Quality"
        }
    }
}

/// The badge under the scrubber: wave glyph + label, as on the phone. Nothing
/// is drawn for YouTube's AAC — the space stays empty rather than announcing
/// the absence of something.
struct StreamQualityBadge: View {
    var label: String?
    var color: Color = .white

    var body: some View {
        if let kind = StreamQualityKind(label: label) {
            HStack(spacing: 5) {
                switch kind {
                case .hiResLossless, .lossless:
                    LosslessWave()
                        .fill(color.opacity(0.85))
                        .frame(width: 15, height: 8)
                case .highQuality:
                    Image(systemName: "headphones")
                        .font(.system(size: 10, weight: .semibold))
                        .foregroundStyle(color.opacity(0.8))
                }
                Text(kind.text)
                    .font(BitFont.font(.medium, 10))
                    .tracking(0.2)
                    .foregroundStyle(color.opacity(0.75))
            }
        }
    }
}
